// Browser integration checks. Refuse to write unless the server is the synthetic S1/Q1/B1 fixture.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(path.join(process.env.AUDIT_PLAYWRIGHT_MODULES, 'playwright'));
const origin = 'http://127.0.0.1:8012';
const output = path.resolve(process.env.AUDIT_REPORT_DIR || 'evaluations/reports/audit-ui-1.4');
fs.mkdirSync(output, {recursive:true});
const checks = [];
const check = name => { checks.push(name); process.stdout.write(name + '\n'); };
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.AUDIT_BROWSER_EXECUTABLE});
  const context = await browser.newContext({viewport:{width:1440,height:1000}, acceptDownloads:true});
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(origin + '/audit'); await page.waitForLoadState('networkidle');
    await page.getByRole('heading', {name:'Synthetic source', exact:true}).waitFor();
    const inventory = await (await page.request.get(origin + '/api/v1/validation/audit/items')).json();
    assert.deepEqual(inventory.items.map(i => i.item_id).sort(), ['B1','Q1','S1']);
    assert.equal(inventory.items.find(i => i.item_id === 'S1').title, 'Synthetic source');
    await page.screenshot({path:path.join(output, 'initial-desktop.png'), fullPage:true});
    fs.writeFileSync(path.join(output, 'initial-dom-summary.json'), JSON.stringify({title:await page.title(), labels:await page.locator('label').allTextContents()}, null, 2));
    if (process.argv.includes('--inspect')) return;
    assert(inventory.items.every(i => i.revision === 0), 'Use a fresh synthetic fixture for each full run');
    check('synthetic_fixture_only');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message').filter({hasText:'请填写候选处理意见'}).waitFor();
    check('incomplete_submission_rejected');
    await page.locator('#field-notes').fill('<img src=x onerror=alert(1)> Synthetic draft');
    await page.getByRole('button', {name:'保存草稿', exact:true}).click();
    await page.locator('#message.success').filter({hasText:'草稿已保存'}).waitFor();
    await page.reload(); await page.waitForLoadState('networkidle');
    await page.locator('#field-notes').waitFor();
    assert.equal(await page.locator('#field-notes').inputValue(), '<img src=x onerror=alert(1)> Synthetic draft');
    check('draft_survives_reload');
    await page.locator('#field-notes').fill('Unsaved local edit');
    page.once('dialog', dialog => dialog.dismiss());
    await page.getByRole('button', {name:'候选题目', exact:true}).click();
    assert.equal(await page.locator('#field-notes').inputValue(), 'Unsaved local edit');
    assert.equal(await page.locator('[data-kind=source]').getAttribute('aria-pressed'), 'true');
    check('unsaved_changes_cancel_navigation');
    async function common() {
      await page.locator('#field-decision').selectOption('accept');
      await page.locator('#field-reviewer').fill('Synthetic UI reviewer');
      await page.getByRole('button', {name:'填入当前时间', exact:true}).click();
      await page.locator('#field-notes').fill('Synthetic review declaration');
    }
    await common();
    for (const name of ['adult_scope','evidence_quality','conflicts_of_interest']) await page.locator('#field-'+name).fill('Synthetic scoped assessment');
    for (const name of ['license_version_confirmed','source_family_aliases_checked']) await page.locator('#field-'+name).selectOption('true');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message.success').filter({hasText:'审核声明已提交'}).waitFor();
    assert((await page.locator('#item-list').textContent()).includes('Synthetic source'));
    check('source_submission_saved');
    await page.getByRole('button', {name:'查看历史', exact:true}).click();
    await page.locator('.audit-history-event').first().waitFor();
    assert.equal(await page.locator('.audit-history-event').count(), 2);
    assert.equal(await page.locator('img').count(), 0);
    assert((await page.locator('#history').textContent()).includes('<img src=x onerror=alert(1)>'));
    check('history_and_untrusted_text_render_safely');
    await page.getByRole('button', {name:'候选题目', exact:true}).click();
    await page.getByRole('heading', {name:'Synthetic question', exact:true}).waitFor();
    await common();
    for (const name of ['question_clarity','adult_applicability','evidence_sufficiency']) await page.locator('#field-'+name).selectOption('true');
    await page.locator('#field-scope_limitations').fill('Synthetic scope only');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message').filter({hasText:'补充证据尚未完成绑定'}).waitFor();
    await page.locator('#field-additional_relevant_evidence').selectOption('none');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message.success').filter({hasText:'审核声明已提交'}).waitFor();
    check('evidence_case_requires_explicit_no_missing_evidence');
    // Clearing a previously confirmed field must remain unconfirmed, rather than silently preserving [].
    await page.locator('#field-additional_relevant_evidence').selectOption('');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message').filter({hasText:'补充证据尚未完成绑定'}).waitFor();
    assert.equal(await page.locator('#field-additional_relevant_evidence').inputValue(), '');
    check('cleared_confirmation_is_not_reaccepted');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#item-list button').filter({hasText:'B1'}).click();
    await page.getByRole('heading', {name:'Synthetic boundary', exact:true}).waitFor();
    assert.equal(await page.locator('#field-evidence_sufficiency').count(), 0);
    await common();
    await page.locator('#field-question_clarity').selectOption('true');
    await page.locator('#field-scope_limitations').fill('Synthetic boundary scope');
    await page.locator('#field-boundary_expected_behavior_confirmed').selectOption('true');
    await page.getByRole('button', {name:'提交审核声明', exact:true}).click();
    await page.locator('#message.success').filter({hasText:'审核声明已提交'}).waitFor();
    check('boundary_form_has_distinct_submission_fields');
    await page.getByRole('button', {name:'资料来源', exact:true}).click();
    await page.getByRole('heading', {name:'Synthetic source', exact:true}).waitFor();
    const sourceURL = origin+'/api/v1/validation/audit/items/source/S1';
    const current = await (await page.request.get(sourceURL)).json();
    const remote = await page.request.post(sourceURL+'/draft', {headers:{Origin:origin}, data:{binding_hash:current.binding_hash, expected_revision:current.revision, review:{notes:'Other page draft'}}});
    assert.equal(remote.status(), 200);
    await page.locator('#field-notes').fill('Local unsaved conflict edit');
    await page.getByRole('button', {name:'保存草稿', exact:true}).click();
    await page.locator('#message').filter({hasText:'另一页面更新'}).waitFor();
    assert.equal(await page.locator('#field-notes').inputValue(), 'Local unsaved conflict edit');
    check('conflict_keeps_local_form');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', {name:'重新载入记录', exact:true}).click();
    await page.locator('#field-notes').filter({visible:true}).waitFor();
    await page.waitForFunction(() => document.querySelector('#field-notes').value === 'Other page draft');
    assert((await page.locator('#item-list').textContent()).includes('Synthetic source'));
    assert((await page.locator('#totals').textContent()).includes('2 / 3'));
    check('explicit_reload_reads_latest_record');
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', {name:'下载审核表', exact:true}).click();
    const download = await downloadPromise; const downloaded = await download.path();
    const exported = JSON.parse(fs.readFileSync(downloaded, 'utf8'));
    assert.equal(exported.clinical_approval, false);
    assert.equal(exported.reviewer_identity_authenticated, false);
    assert.equal(exported.source_review.sources[0].review.decision, undefined);
    assert.equal(exported.case_review.cases.length, 2);
    check('download_excludes_drafts_and_never_grants_approval');
    await page.getByRole('button', {name:'查看历史', exact:true}).click();
    await page.locator('.audit-history-event').first().waitFor();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path:path.join(output, 'desktop.png'), fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output, 'mobile.png'), fullPage:true});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    check('mobile_layout_no_horizontal_overflow');
    assert.deepEqual(errors, []); check('no_browser_javascript_errors');
    fs.writeFileSync(path.join(output, 'browser-check.json'), JSON.stringify({passed:true, synthetic_fixture_only:true, checks, console_errors:errors}, null, 2));
  } catch (error) {
    await page.screenshot({path:path.join(output, 'failure.png'), fullPage:true}).catch(()=>{});
    fs.writeFileSync(path.join(output, 'browser-check-failed.json'), JSON.stringify({passed:false, checks, error:String(error)}, null, 2));
    throw error;
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
